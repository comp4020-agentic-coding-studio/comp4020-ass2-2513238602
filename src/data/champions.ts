const focusByTag: Record<string, string> = {
  Marksman: "approach path, range break, and exit after commitment",
  Mage: "spell zone, key cooldown, and the window to enter",
  Assassin: "burst threshold, flank timing, and peel responsibility",
  Tank: "crowd-control chain, durability window, and target access",
  Support: "peel or disengage tool that can deny the engage",
  Fighter: "extended-trade breakpoint and second-rotation timing",
};

export const champions = rosterSource.split("\n").map((row) => {
  const [id, name, rawTags] = row.split("|");
  const tags = rawTags.split(",");
  const focus = focusByTag[tags[0]] ?? "main threat, response window, and exit condition";
  return {
    id,
    name,
    tags,
    lanePool: courseTopPool.has(id),
    priority: volibearPriorityQueue.has(id),
    focus,
  };
});

export type Champion = (typeof champions)[number];
